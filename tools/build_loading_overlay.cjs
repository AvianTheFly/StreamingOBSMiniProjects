// Finite local publisher. Keep source policy/art/clock owners separate while
// shipping one browser entry supported by already-running Hub HTTP servers.
const fs=require('node:fs'),path=require('node:path');
const web=path.resolve(__dirname,'../mini projects/league_api/stage_web');
function source(name){return fs.readFileSync(path.join(web,name),'utf8').replace(/^\uFEFF/,'');}
function local(source){
  return source.replace(/^import .*;\r?\n/gm,'').replace(/^export (const|class) /gm,'$1 ');
}
const ceremony=source('loading-ceremony.js'),art=source('loading-art.js'),motion=source('loading-motion.js');
if(!art.includes("import {PaintedPatch} from '/shared/world-motion.js';"))throw Error('Review changed shared artwork contract');
const body="// Generated by tools/build_loading_overlay.cjs; edit the loading source owners.\nimport {PaintedPatch} from '/shared/world-motion.js';\n"+local(ceremony)+'\n'+local(art)+'\n'+local(motion);
if(/^import .* from ['"]\.\//m.test(body))throw Error('Unbundled feature import');
const target=path.join(web,'loading-effects.js');
if(process.argv.includes('--check')){
  if(source('loading-effects.js')!==body)throw Error('Loading browser entry is stale; run the publisher');
  console.log('Loading browser entry matches its source owners.');
}else{fs.writeFileSync(target,body,'utf8');console.log('Published loading browser entry from ceremony, art and motion owners.');}
