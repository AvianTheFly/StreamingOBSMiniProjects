// Offline preparation of connected alpha silhouettes; preserve the original atlas.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),sharp=require('sharp');
const root=path.resolve(__dirname,'../mini projects/scene_voice_switcher/web');
(async()=>{
 const input=fs.readFileSync(path.join(root,'art/league-guests-v1.png'));
 const {data,info}=await sharp(input).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const {width:w,height:h}=info,labels=new Uint32Array(w*h),queue=new Uint32Array(w*h),parts=[];let serial=0;
 for(let start=0;start<w*h;start++){
  if(labels[start]||data[start*4+3]<32)continue;
  const id=++serial;let head=0,tail=1,left=w,top=h,right=0,bottom=0;queue[0]=start;labels[start]=id;
  while(head<tail){const p=queue[head++],x=p%w,y=Math.floor(p/w);left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
   for(const n of [x?p-1:-1,x<w-1?p+1:-1,y?p-w:-1,y<h-1?p+w:-1])if(n>=0&&!labels[n]&&data[n*4+3]>=32){labels[n]=id;queue[tail++]=n;}}
  if(tail>10000)parts.push({id,count:tail,left,top,right,bottom});
 }
 if(parts.length!==12)throw Error('Expected 12 independent silhouettes, found '+parts.length);
 parts.sort((a,b)=>a.top-b.top);const assets={};
 for(const [row,name] of ['udyr','poro','scuttle','teemo'].entries()){
  const poses=parts.slice(row*3,row*3+3).sort((a,b)=>a.left-b.left);
  for(const [pose,p] of poses.entries()){
   const width=p.right-p.left+1,height=p.bottom-p.top+1,output=Buffer.alloc(width*height*4);
   for(let y=0;y<height;y++)for(let x=0;x<width;x++){const pos=(y+p.top)*w+x+p.left;if(labels[pos]===p.id)data.copy(output,(y*width+x)*4,pos*4,pos*4+4);}
   const file=`league-${name}-${pose}.png`;await sharp(output,{raw:{width,height,channels:4}}).png().toFile(path.join(root,'art/prepared',file));
   (assets[name]??=[]).push({url:'./art/prepared/'+file,width,height});
  }
 }
 fs.writeFileSync(path.join(root,'league-guest-assets.js'),'// Generated by tools/prepare_league_guests.cjs.\nexport const atlasHash='+JSON.stringify(crypto.createHash('sha256').update(input).digest('hex'))+';\nexport const leagueAssets='+JSON.stringify(assets,null,2)+';\n');
 console.log('Prepared 12 intact League poses from connected silhouettes.');
})().catch(e=>{console.error(e);process.exitCode=1;});
