def _parse_hotkey_sequence(raw: str) -> list[str]:
    text = str(raw or "").strip().lower()
    if not text:
        return []
    for sep in (",", "+", ";"):
        text = text.replace(sep, " ")
    parts = [part for part in text.split() if part]
    if len(parts) > 1:
        return parts
    return list(parts[0]) if parts else []


def _scan_audio_assets(asset_dir: Path | None, valid_extensions: set[str] | None) -> list[str]:
    if asset_dir is None or not asset_dir.is_dir():
        return []
    allowed = {str(ext).lower() for ext in (valid_extensions or set())}
    stems: list[str] = []
    for path in sorted(asset_dir.iterdir(), key=lambda item: item.name.lower()):
        if not path.is_file():
            continue
        if allowed and path.suffix.lower() not in allowed:
            continue
        stems.append(path.stem)
    return stems


