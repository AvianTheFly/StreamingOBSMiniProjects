def _broadcast(event_type: str, payload: dict) -> None:
    msg = f"data: {json.dumps({'type': event_type, 'payload': payload})}\n\n"
    encoded = msg.encode("utf-8")
    with _sse_lock:
        for q in list(_sse_clients):
            try:
                q.put_nowait(encoded)
            except queue.Full:
                pass


