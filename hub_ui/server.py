def _obs_input_settings(source_name: str) -> dict[str, Any]:
    try:
        import obs
    except Exception:
        return {}

    client = obs.get_obs()
    try:
        resp = client.send("GetInputSettings", {"inputName": source_name}, raw=True)
    except TypeError:
        try:
            resp = client.send("GetInputSettings", {"inputName": source_name})
        except Exception:
            return {}
    except Exception:
        return {}

    if isinstance(resp, dict):
        settings = resp.get("inputSettings") or resp.get("input_settings") or {}
        return settings if isinstance(settings, dict) else {}
    settings = getattr(resp, "input_settings", None) or getattr(resp, "inputSettings", None) or {}
    return settings if isinstance(settings, dict) else {}


def _obs_source_matches_runtime_stem(source_name: str, stem: str) -> bool:
    try:
        import obs
    except Exception:
        return False

    stem = str(stem or "").strip()
    if not stem:
        return False

    try:
        state = obs.get_media_state(source_name)
    except Exception:
        return False
    if state not in _ACTIVE_MEDIA_STATES:
        return False

    settings = _obs_input_settings(source_name)
    local_file = str(settings.get("local_file") or "").strip()
    if not local_file:
        return False

    return Path(local_file).stem.casefold() == stem.casefold()


def _sync_audio_memory_from_obs(project_key: str | None = None) -> set[str]:
    changed: set[str] = set()
    try:
        import obs
        from lib.project_registry import discover_editor_projects
    except Exception:
        return changed

    projects = discover_editor_projects()
    runtime_bindings = _runtime_audio_bindings()

    for key, project_info in projects.items():
        if project_key and key != project_key:
            continue
        runtime = runtime_bindings.get(key) or {}
        context = _project_audio_context(key, project_info, runtime=runtime)
        if context is None:
            continue

        state_file, state, profile_name, current_stem, source_name = context
        if not _obs_source_matches_runtime_stem(source_name, current_stem):
            continue
        volume = obs.get_input_volume(source_name) or {}
        live_db = volume.get("db")
        if live_db is None:
            continue

        profiles = state["profiles"]
        profile = profiles[profile_name]
        project_db = float(profile.get("project_volume_db") or 0.0)
        profile_db = float(profile.get("profile_volume_db") or 0.0)
        offsets = profile.setdefault("file_volume_offsets", {})
        if not isinstance(offsets, dict):
            offsets = {}
            profile["file_volume_offsets"] = offsets

        next_offset = round(float(live_db) - project_db - profile_db, 2)
        prev_offset = float(offsets.get(current_stem, 0.0) or 0.0)
        if abs(prev_offset - next_offset) <= 0.05:
            continue

        if abs(next_offset) <= 0.05:
            offsets.pop(current_stem, None)
        else:
            offsets[current_stem] = next_offset

        _write_json_object(state_file, state)
        changed.add(key)

    return changed


def _apply_live_audio_to_obs(project_key: str) -> bool:
    try:
        import obs
        from lib.project_registry import discover_editor_projects
    except Exception:
        return False

    project_info = discover_editor_projects().get(project_key)
    if project_info is None:
        return False

    runtime = _runtime_audio_bindings().get(project_key) or {}
    context = _project_audio_context(project_key, project_info, runtime=runtime)
    if context is None:
        return False

    _state_file, state, profile_name, current_stem, source_name = context
    if not _obs_source_matches_runtime_stem(source_name, current_stem):
        return False
    profiles = state["profiles"]
    profile = profiles[profile_name]
    offsets = profile.get("file_volume_offsets") if isinstance(profile.get("file_volume_offsets"), dict) else {}
    project_db = float(profile.get("project_volume_db") or 0.0)
    profile_db = float(profile.get("profile_volume_db") or 0.0)
    file_db = float(offsets.get(current_stem, 0.0) or 0.0)
    effective_db = round(project_db + profile_db + file_db, 2)
    obs.set_input_volume_db(source_name, effective_db)
    return True


