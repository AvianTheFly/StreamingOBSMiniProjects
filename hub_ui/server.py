class HubUIServer:
    def __init__(self, port: int = 7420, editor_port: int = 8765) -> None:
        self.port        = port
        self.editor_port = editor_port

    def serve(self, stop_event: threading.Event) -> None:
        """Start the HTTP server and status-poll thread; block until stop_event."""
        # Subscribe to events.py bus ÃƒÂ¢Ã¢â€šÂ¬Ã¢â‚¬Â forward everything to SSE clients
        try:
            import events as hub_events
            _EVENT_NAMES = [
                "coordinator.project_paused",
                "coordinator.play_cleared",
                "coordinator.project_resumed",
                "game.connected",
                "game.disconnected",
                "sfx.play",
            ]
            def _forward(data: dict, *, _event_name: str) -> None:
                _broadcast("hub_event", {"event": _event_name, "data": data})

            _handlers = {}
            for ev in _EVENT_NAMES:
                cb = lambda data, _en=ev: _forward(data, _event_name=_en)
                _handlers[ev] = cb
                hub_events.subscribe(ev, cb)
        except Exception:
            _handlers = {}

        # Start status-poll thread
        poll_thread = threading.Thread(
            target=_poll_loop, args=(stop_event,), daemon=True, name="hub_ui:poll"
        )
        poll_thread.start()

        hotkey_thread = threading.Thread(
            target=_hub_hotkey_loop,
            args=(stop_event,),
            daemon=True,
            name="hub_ui:hotkeys",
        )
        hotkey_thread.start()

        # Start HTTP server
        server = http.server.ThreadingHTTPServer(("", self.port), _Handler)
        server._editor_port = self.editor_port  # accessible via self.server in handler
        server_thread = threading.Thread(
            target=server.serve_forever, daemon=True, name="hub_ui:http"
        )
        server_thread.start()
        print(f"[hub_ui] Serving on port {self.port}")

        # Block until shutdown
        stop_event.wait()
        server.shutdown()

        # Unsubscribe event handlers
        try:
            import events as hub_events
            for ev, cb in _handlers.items():
                hub_events.unsubscribe(ev, cb)
        except Exception:
            pass
